/// (name, svg) for an uppercase ISO code.
pub fn lookup(code: &str) -> Option<(&'static str, &'static str)> {
    FLAGS
        .binary_search_by(|f| f.0.cmp(code))
        .ok()
        .map(|i| (FLAGS[i].1, FLAGS[i].2))
}
